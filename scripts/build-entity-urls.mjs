/**
 * Stage 2 of the URL namespace: generate the pretty per-club folders.
 *
 *   referee-tool.com/neconn/            the schedule (hub later — see NOTE)
 *   referee-tool.com/neconn/schedule    the schedule
 *   referee-tool.com/neconn/portal      submit games, request changes
 *   referee-tool.com/neconn/pay         pay referees
 *   referee-tool.com/neconn/audit       invoices, stats, contract
 *
 * Paths are named by FUNCTION, never by entity type or job title. Tod's rule,
 * from "if we cut over to high school assigning that won't work" — a high
 * school isn't a club and doesn't have a president. /portal not /club,
 * /audit not /president. Nothing here has to be renamed when the entity
 * type changes, which matters because a renamed folder is a dead link and
 * these will have been handed out by then.
 *
 * ── WHY THE SCHEDULE STUBS ARE 15 LINES ─────────────────────────────────────
 * They are NOT copies of the schedule page. They set the club and load the
 * shared /schedules/club.css and /schedules/club.js. A bug fix in those two
 * files reaches every club instantly — no regeneration, no staleness. This
 * script only needs rerunning when a club is ADDED or a portal toggled.
 *
 * Both lowercase and UPPERCASE folders are written. Paths are case-sensitive
 * on GitHub Pages, and half the club names are acronyms people capitalise by
 * instinct (NECONN, WAM, KOVA, RHAMYS). Lowercase is canonical.
 *
 * Run without --write for a preview.
 */
import { createClient } from '@supabase/supabase-js';
import fs from 'fs';
import path from 'path';

const db = createClient('https://kaniccdqieyesezpousu.supabase.co',
                        'sb_publishable_pJX6Fsg4YrSNEhfNTHbkLA_tzFJmEUb');
const WRITE = process.argv.includes('--write');
const ROOT  = path.resolve(process.cwd());

// Anything already at the repo root. A club slug colliding with one of these
// would shadow a real page, so we refuse rather than overwrite.
//
// Except our own output. After the first run every club folder exists, and a
// naive check treats them as collisions and refuses to update them — which is
// exactly what happened: the second run skipped every club it had just built.
// A directory holding our stamp is ours to rewrite.
// Declared before RESERVED uses it — const is not hoisted, and an earlier
// version referenced this from above with a try/catch that swallowed the
// resulting ReferenceError, so every club folder silently read as "not ours"
// and the second run refused to update any of them.
const STAMP_MARK = 'GENERATED by scripts/build-entity-urls.mjs';
const STAMP = `<!-- ${STAMP_MARK} — do not edit by hand. -->`;
// The script was called build-club-urls.mjs when the first folders were written.
// Recognise that stamp too, or every existing folder reads as "not ours" and the
// next run refuses to touch it.
const OWN_STAMPS = [STAMP_MARK, 'GENERATED by scripts/build-club-urls.mjs'];

const isGenerated = dir => {
  const walk = d => fs.readdirSync(d, { withFileTypes: true }).some(e =>
    e.isDirectory() ? walk(path.join(d, e.name))
                    : e.name === 'index.html' && OWN_STAMPS.some(m => fs.readFileSync(path.join(d, e.name), 'utf8').includes(m)));
  // Only an unreadable directory is non-fatal here. Anything else is a bug and
  // must not be turned into a quiet "false".
  try { return walk(dir); }
  catch (e) { if (e.code === 'EACCES' || e.code === 'ENOENT') return false; throw e; }
};
// Only DIRECTORIES conflict. A root .html file does not: /girls-summer-league/
// and /girls-summer-league.html are distinct URLs and a static host serves both
// happily. Treating the basename as taken blocked Girls Summer League from
// having a namespace at all, for no reason.
const RESERVED = new Set(
  fs.readdirSync(ROOT)
    .filter(f => fs.statSync(path.join(ROOT, f)).isDirectory())
    .filter(f => !isGenerated(path.join(ROOT, f)))
    .map(s => s.toLowerCase()));

// Test clubs get no public URL. Nothing in the data marks them — club_type is
// "managed" for almost everything and `enabled` is false even for NECONN — so
// this has to be stated. Matched on the slug.
// ⚠️ KOVA carries 12 games in the games table despite being a test club.
const TEST_CLUBS = new Set(["kova"]);

// ⛔ HANDS OFF. Girls Summer League has its own long-standing public page and
// is not to be touched — not replaced, not redirected to, not namespaced.
// Tod, twice: "we don't need to mess with girls summer league."
const HANDS_OFF = new Set(['girls-summer-league']);

// A real page: sets the club, loads the shared CSS and JS. Nothing else.
const scheduleStub = (clubName, title) => `<!DOCTYPE html>
<html lang="en">
${STAMP}
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(title)} — Schedule</title>
<link rel="canonical" href="https://referee-tool.com/${slugOf(clubName)}/schedule">
<link rel="stylesheet" href="/css/styles.css">
<link rel="stylesheet" href="/schedules/club.css?v=1">
</head>
<body>
<div id="clubSchedule"></div>
<script>window.CLUB_SLUG = ${JSON.stringify(clubName)};</script>
<script src="/config.js"></script>
<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2"></script>
<script src="/js/supabase-client.js?v=14"></script>
<script src="/schedules/club.js?v=1"></script>
</body>
</html>
`;

// The portals are 8,000-line applications — duplicating them per club is out of
// the question, so these are redirects. The address bar flips, which is fine:
// they're tools a coordinator logs into, not links read over the phone.
// meta-refresh and a real anchor are there for no-JS and for anything that
// follows the page without running scripts.
const redirectStub = (target, label, title) => `<!DOCTYPE html>
<html lang="en">
${STAMP}
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${esc(target)}">
<title>${esc(title)} — ${esc(label)}</title>
</head>
<body style="font-family:system-ui,sans-serif;background:#060e20;color:#dfe7f5;padding:48px 20px;text-align:center;">
<script>location.replace(${JSON.stringify(target)});</script>
<p>Taking you to the ${esc(label)}…</p>
<p><a href="${esc(target)}" style="color:#00c853;font-weight:700;">Continue</a></p>
</body>
</html>
`;

function esc(s) {
  return String(s == null ? '' : s).replace(/[&<>"]/g, c => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;' }[c]));
}
// Some clubs carry their own type in the name — "KOVA Soccer Club" would give
// /kova-soccer-club/ while NECONN gives /neconn/. Inconsistent, and long enough
// to defeat the point of doing this at all. Strip the trailing type words; a
// collision check below refuses to run if two clubs land on the same slug.
const TYPE_TAIL = /[\s-]+(youth[\s-]+soccer[\s-]+club|athletic[\s-]+association|youth[\s-]+soccer|soccer[\s-]+club|soccer[\s-]+association|soccer|sc|ysc)$/i;
function slugOf(name) {
  let s = String(name || '').trim();
  const stripped = s.replace(TYPE_TAIL, '').trim();
  if (stripped) s = stripped;               // never strip a name down to nothing
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

const B = 'https://referee-tool.com';

const [clubsRes, eventsRes, tournsRes] = await Promise.all([
  db.from('clubs').select('id,name,"Club Name","Display Name","Club Game Upload",schedule_page_enabled,payment_portal_enabled,president,"President Email"'),
  db.from('events').select('id,name,"Club Name","Display Name",slug,enabled,schedule_url,avail_form_enabled,payment_portal_enabled'),
  db.from('tournaments').select('id,name,key,status'),
]);
for (const [label, r] of [['clubs', clubsRes], ['events', eventsRes], ['tournaments', tournsRes]])
  if (r.error) { console.log(`load ${label} failed:`, r.error.message); process.exit(1); }

// ── Build one list across all three entity types ────────────────────────────
// The function words are deliberately the same everywhere — /schedule, /portal,
// /pay mean the same thing whether the org is a club, an event or a tournament.
// Only what's actually behind them differs. That's the point of naming paths by
// function: nothing has to be renamed when the entity type changes.
const entities = [];

for (const c of (clubsRes.data || [])) {
  const name = c['Club Name'] || c.name; if (!name) continue;
  const slug = slugOf(name); if (!slug) continue;
  const pages = {};
  if (c.schedule_page_enabled) {
    pages['schedule'] = scheduleStub(name, c['Display Name'] || name);
    pages['']         = scheduleStub(name, c['Display Name'] || name);   // hub replaces this later
  }
  const submit = c['Club Game Upload'] || `${B}/club-game-submit.html?club=${slug}`;
  if (c['Club Game Upload']) {
    pages['portal'] = ['Club Portal', submit];
    if (c.payment_portal_enabled) pages['pay'] = ['Pay Portal', `${submit}&pay=portal`];
  }
  if (c.president || c['President Email'])
    pages['audit'] = ['Audit Portal', `${B}/presidents-portal.html?club=${slug}`];
  entities.push({ kind: 'club', name, slug, title: c['Display Name'] || name, pages });
}

for (const e of (eventsRes.data || [])) {
  const name = e['Club Name'] || e.name; const slug = (e.slug || '').trim();
  if (!name || !slug || e.enabled === false) continue;
  const pages = {};
  // Events keep a stored schedule_url — Girls Summer League points at its own
  // long-standing public page, which this redirects to rather than replaces.
  if (e.schedule_url) {
    pages['schedule'] = ['Schedule', e.schedule_url];
    pages['']         = ['Schedule', e.schedule_url];
  }
  pages['portal'] = ['Event Portal', `${B}/club-game-submit.html?club=${slug}`];
  if (e.avail_form_enabled)     pages['availability'] = ['Availability Form', `${B}/referee-availability-form.html?event=${slug}`];
  if (e.payment_portal_enabled) pages['pay']          = ['Pay Portal', `${B}/club-game-submit.html?club=${slug}&pay=portal`];
  entities.push({ kind: 'event', name, slug, title: e['Display Name'] || name, pages });
}

for (const t of (tournsRes.data || [])) {
  const name = t.name; const slug = (t.key || '').trim();
  if (!name || !slug) continue;
  entities.push({ kind: 'tournament', name, slug, title: name, pages: {
    'schedule': ['Schedule',          `${B}/tournament-schedule.html?key=${slug}`],
    '':         ['Schedule',          `${B}/tournament-schedule.html?key=${slug}`],
    'portal':   ['Tournament Portal', `${B}/club-game-submit.html?tournament=${slug}`],
    'pay':      ['Pay Portal',        `${B}/tournament-pay-portal.html?key=${slug}`],
  }});
}

// ── Collisions, now across ALL THREE types ──────────────────────────────────
// A tournament named after the club that hosts it would otherwise silently
// overwrite that club's folder.
const bySlug = {};
entities.forEach(e => { (bySlug[e.slug] = bySlug[e.slug] || []).push(`${e.name} (${e.kind})`); });
const clashes = Object.entries(bySlug).filter(([, v]) => v.length > 1);
if (clashes.length) {
  console.log('❌ slug collision — these would share a folder:');
  clashes.forEach(([s, v]) => console.log(`   /${s}/  ← ${v.join('  +  ')}`));
  console.log('Nothing written. Give one of them an explicit slug first.');
  process.exit(1);
}

let planned = 0, skipped = [];
const plan = [];

for (const ent of entities) {
  if (HANDS_OFF.has(ent.slug))  { skipped.push(`${ent.name} → hands off, already has its own page`); continue; }
  if (TEST_CLUBS.has(ent.slug)) { skipped.push(`${ent.name} → test ${ent.kind}, no public URL`); continue; }
  if (RESERVED.has(ent.slug))   { skipped.push(`${ent.name} → /${ent.slug}/ collides with an existing page or folder`); continue; }
  if (!Object.keys(ent.pages).length) { skipped.push(`${ent.name} → nothing enabled yet`); continue; }

  for (const [sub, val] of Object.entries(ent.pages)) {
    // A real page (already rendered HTML) or a [label, target] redirect.
    const html = typeof val === 'string' ? val : redirectStub(val[1], val[0], ent.title);
    plan.push({ file: path.join(ROOT, ent.slug, sub, 'index.html'), html });
  }

  planned++;
  console.log(`${ent.title}  [${ent.kind}]`);
  console.log(`   /${ent.slug}/  → ${Object.keys(ent.pages).map(p => p || '(root)').join(', ')}`);
}

// Uppercase twins are NOT written. Windows is case-insensitive, so writing
// /NECONN/ on top of /neconn/ just overwrites it — the first run reported 56
// files when 28 landed. Catching a capitalised acronym needs the 404.html
// path-normaliser instead, which handles every casing rather than two.
console.log(`\n${planned} entities → ${plan.length} files`);
if (skipped.length) { console.log('\nskipped:'); skipped.forEach(s => console.log('   ' + s)); }

// Refuse to clobber anything we did not generate ourselves.
const collisions = plan.filter(p => fs.existsSync(p.file)
  && !OWN_STAMPS.some(m => fs.readFileSync(p.file, 'utf8').includes(m)));
if (collisions.length) {
  console.log(`\n❌ ${collisions.length} target file(s) exist and were NOT generated by this script:`);
  collisions.forEach(c => console.log('   ' + c.file));
  console.log('Refusing to overwrite. Nothing written.');
  process.exit(1);
}

if (!WRITE) { console.log('\n──────── PREVIEW ONLY — nothing written. Re-run with --write. ────────'); process.exit(0); }

for (const p of plan) {
  fs.mkdirSync(path.dirname(p.file), { recursive: true });
  fs.writeFileSync(p.file, p.html, 'utf8');
}
console.log(`\nwrote ${plan.length} files.`);
